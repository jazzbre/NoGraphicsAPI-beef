"""Generate the C ABI bridge and Beef bindings from the checked-out headers."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

PROJECT_DIRECTORY = Path(__file__).resolve().parent.parent
SPAN_ELEMENTS = {
    'UInt32Span': 'uint32',
    'ColorTargetSpan': 'ColorTargetDesc',
    'ColorAttachmentSpan': 'ColorAttachment',
    'CommandBufferSpan': 'CommandBuffer*',
    'ByteSpan': 'byte',
}
TYPE_REPLACEMENTS = {
    'Span<const uint32>': 'UInt32Span',
    'Span<const ColorTargetDesc>': 'ColorTargetSpan',
    'Span<const ColorAttachment>': 'ColorAttachmentSpan',
    'Span<CommandBuffer*const>': 'CommandBufferSpan',
    'GpuCpuRange<byte>': 'GpuCpuRange',
    'HeapAllocation<byte>': 'HeapAllocation',
}
PRIMITIVE_TYPES = {'void', 'bool', 'char', 'float', 'double', 'byte', 'size_t'} | {
    prefix + str(width) for prefix in ('int', 'uint') for width in (8, 16, 32, 64)
}
BEEF_KEYWORDS = set('''abstract align alignof append as asm base bool box break case catch char char8 char16 char32
    checked class comptime const continue default defer delegate delete do double else enum event explicit extension extern
    false finally fixed float for foreach function goto if implicit in int interface internal is let long mixin namespace
    new null object operator out override params private protected public readonly ref repeat return sbyte scope sealed
    short signed sizeof static struct switch this throw true try type typealias typeof uint ulong unchecked union unsigned
    ushort using var virtual void volatile when where while yield'''.split())
GENERATED_NOTICE = '// Generated by tools/generate_bindings.py. Edit the generator instead.\n'


def remove_comments(source):
    return re.sub(r'//[^\n]*|/\*.*?\*/', '', source, flags=re.S)


def read_namespace(header_path):
    source = remove_comments(header_path.read_text(encoding='utf-8'))
    if re.search(r'^\s*#(?!include\b|pragma once\b)', source, flags=re.M):
        raise ValueError('Conditional or unsupported preprocessor directive in ' + str(header_path))
    source = re.sub(r'^\s*#[^\n]*', '', source, flags=re.M).strip()
    namespace = re.fullmatch(r'namespace\s+gpu\s*\{(.*)\}', source, flags=re.S)
    if not namespace:
        raise ValueError('Unsupported namespace or preprocessor structure in ' + str(header_path))
    return namespace.group(1)


def split_declarations(source):
    declarations = []
    brace_depth = 0
    parenthesis_depth = 0
    declaration_start = 0
    for position, character in enumerate(source):
        if character == '(':
            parenthesis_depth += 1
        elif character == ')':
            parenthesis_depth -= 1
        elif character == '{':
            brace_depth += 1
        elif character == '}':
            brace_depth -= 1
            if brace_depth == 0 and parenthesis_depth == 0:
                declaration = source[declaration_start:position + 1].strip()
                if not re.match(r'(?:template\s*<[^>]+>\s*)?(?:struct|class|enum)\b', declaration) and re.search(r'\)\s*noexcept\s*\{', declaration):
                    declarations.append(declaration)
                    declaration_start = position + 1
        elif character == ';' and brace_depth == 0 and parenthesis_depth == 0:
            declarations.append(source[declaration_start:position + 1].strip())
            declaration_start = position + 1
        if brace_depth < 0 or parenthesis_depth < 0:
            raise ValueError('Unbalanced C++ declaration')
    if brace_depth or parenthesis_depth or source[declaration_start:].strip():
        raise ValueError('Incomplete C++ declaration: ' + source[declaration_start:].strip()[:120])
    return declarations


def normalize_type(type_name):
    type_name = re.sub(r'\s+', ' ', type_name.strip())
    type_name = re.sub(r'\s*([<>,*&])\s*', r'\1', type_name)
    type_name = type_name.replace('>const', '> const')
    return TYPE_REPLACEMENTS.get(type_name, type_name)


def plain_type(type_name):
    return re.sub(r'\bconst\b', '', type_name).replace('&', '').strip()


def pascal_case(identifier):
    return ''.join(part[:1].upper() + part[1:] for part in identifier.split('_'))


def beef_identifier(identifier):
    return '@' + identifier if identifier in BEEF_KEYWORDS else identifier


def parse_fields(structure_body):
    fields = []
    for declaration in split_declarations(structure_body):
        declaration = declaration.rstrip(';')
        nesting_depth = 0
        for character in declaration:
            if character in '({[':
                nesting_depth += 1
            elif character in ')}]':
                nesting_depth -= 1
            elif character == ',' and nesting_depth == 0:
                raise ValueError('Multiple fields in one declaration are unsupported: ' + declaration)
        declaration = declaration.split('=', 1)[0].strip()
        declaration = re.sub(r'\{\s*\}$', '', declaration).strip()
        field = re.fullmatch(r'([\w\s<>*,]+?)\s+(\w+)', declaration)
        if not field:
            raise ValueError('Unsupported structure field: ' + declaration)
        fields.append((normalize_type(field.group(1)), field.group(2)))
    return fields


def parse_enum_members(enum_body):
    members = []
    previous_name = None
    for declaration in enum_body.split(','):
        if not declaration.strip():
            continue
        member = re.fullmatch(r'\s*(\w+)\s*(?:=\s*(.*))?', declaration)
        if not member:
            raise ValueError('Unsupported enum member: ' + declaration)
        member_name, expression = member.groups()
        if expression is None:
            expression = previous_name + ' + 1' if previous_name else '0'
        expression_without_suffixes = re.sub(r'(?<=[0-9a-fA-F])(?:ull|llu|ul|lu|u|ll)\b', '', expression, flags=re.I)
        remaining_expression = re.sub(r'\b(?:0[xX][0-9a-fA-F]+|[0-9]+)\b', '', expression_without_suffixes)
        for known_name, _, _ in members:
            remaining_expression = re.sub(r'\b' + known_name + r'\b', '', remaining_expression)
        if re.sub(r'[\s()+\-~|&^<>]', '', remaining_expression):
            raise ValueError('Unsupported enum expression: ' + expression)
        members.append((member_name, expression, expression_without_suffixes))
        previous_name = member_name
    return members


def load_api(submodule_directory, utility_configuration):
    for header_name, expected_hash in utility_configuration['support_header_hashes'].items():
        header_source = remove_comments((submodule_directory / header_name).read_text(encoding='utf-8'))
        actual_hash = hashlib.sha256(re.sub(r'\s+', '', header_source).encode('utf-8')).hexdigest()
        if actual_hash != expected_hash:
            raise ValueError(header_name + ': support types changed; review their ABI mappings before regenerating')
    opaque_types = []
    enumerations = []
    structures = {}
    functions = []
    inline_helpers = []
    declarations = split_declarations(read_namespace(submodule_directory / 'include/NoGraphicsAPI/NoGraphicsAPI.hpp'))
    for declaration in declarations:
        forward = re.fullmatch(r'struct\s+(\w+)\s*;', declaration)
        enumeration = re.fullmatch(r'enum class\s+(\w+)\s*:\s*(\w+)\s*\{(.*)\}\s*;', declaration, flags=re.S)
        structure = re.fullmatch(r'(template\s*<[^>]+>\s*)?struct\s+(\w+)\s*\{(.*)\}\s*;', declaration, flags=re.S)
        if forward:
            opaque_types.append(forward.group(1))
        elif enumeration:
            enumeration_name, underlying_type, body = enumeration.groups()
            if underlying_type not in PRIMITIVE_TYPES:
                raise ValueError('Unsupported enum storage: ' + underlying_type)
            enumerations.append((enumeration_name, underlying_type, parse_enum_members(body)))
        elif structure:
            template, structure_name, body = structure.groups()
            if template:
                if structure_name != 'GpuCpuRange' or re.sub(r'\s+', '', template) != 'template<typenameT>':
                    raise ValueError('Unsupported structure template: ' + structure_name)
                body = re.sub(r'\bT\b', 'byte', body)
            structures[structure_name] = parse_fields(body)
        else:
            signature = re.sub(r'\[\[nodiscard\]\]\s*|\bconstexpr\s+', '', declaration)
            if signature.startswith('template') or 'operator|' in signature:
                inline_helpers.append(re.sub(r'\s+', '', signature.split('noexcept', 1)[0]))
                continue
            function = re.fullmatch(r'([\w\s<>*&]+?)\s+(\w+)\((.*?)\)\s*noexcept\s*(?:;|\{.*\})', signature, flags=re.S)
            if not function:
                raise ValueError('Unsupported API declaration: ' + declaration[:160])
            return_type, function_name, parameters = function.groups()
            if function_name == 'gpu_range':
                inline_helpers.append(re.sub(r'\s+', '', signature.split('noexcept', 1)[0]))
            else:
                functions.append((normalize_type(return_type), function_name, parameters, None))
    expected_helpers = {
        'TextureUsageoperator|(TextureUsagelhs,TextureUsagerhs)',
        'Stageoperator|(Stagelhs,Stagerhs)',
        'Accessoperator|(Accesslhs,Accessrhs)',
        'template<typenameT>GpuRangegpu_range(GpuCpuRange<T>range)',
        'GpuRangegpu_range(constGpuHeap&heap)',
    }
    if set(inline_helpers) != expected_helpers:
        raise ValueError('Inline/template helpers changed; update their explicit adapters in the generator')
    for header_name, expected_hash in utility_configuration['public_api_hashes'].items():
        header_source = read_namespace(submodule_directory / 'utility/include/NoGraphicsAPIUtility' / header_name)
        public_section = header_source.split('public:', 1)[1].split('private:', 1)[0]
        actual_hash = hashlib.sha256(re.sub(r'\s+', '', public_section).encode('utf-8')).hexdigest()
        if actual_hash != expected_hash:
            raise ValueError(header_name + ': utility public API changed; review tools/utility_bindings.json adapters before regenerating')
        for declaration in split_declarations(header_source):
            structure = re.fullmatch(r'(?:template\s*<typename T>\s*)?struct\s+(HeapAllocation|PlacedTexture)\s*\{(.*)\}\s*;', declaration, flags=re.S)
            if structure:
                structures[structure.group(1)] = parse_fields(re.sub(r'\bT\b', 'byte', structure.group(2)))
    opaque_types.extend(['BumpAllocator', 'HeapAllocator', 'TextureAllocator', 'DeleteQueue'])
    functions.extend(tuple(function) for function in utility_configuration['functions'])
    function_names = [function[1] for function in functions]
    if len(function_names) != len(set(function_names)):
        raise ValueError('Overloaded or duplicate functions require explicit C ABI names')
    return opaque_types, enumerations, structures, functions


def generate_bindings(submodule_directory, utility_configuration):
    opaque_types, enumerations, structures, functions = load_api(submodule_directory, utility_configuration)
    structure_fields = dict(structures)
    for span_name, element_type in SPAN_ELEMENTS.items():
        structure_fields[span_name] = [(element_type + '*', 'data'), ('size_t', 'size')]
    known_types = set(opaque_types) | set(structure_fields) | {name for name, _, _ in enumerations} | {'DeleteCallback'}

    def validate_type(type_name):
        remaining_type = re.sub(r'\bconst\b|[*&\s]', '', type_name)
        if remaining_type not in known_types | PRIMITIVE_TYPES:
            raise ValueError('Unsupported type: ' + type_name)

    def c_type(type_name):
        type_name = normalize_type(type_name)
        validate_type(type_name)
        return re.sub(r'\b\w+\b', lambda match: (
            'nga_' + match.group() if match.group() in known_types else
            'uint8_t' if match.group() == 'byte' else
            match.group() + '_t' if re.fullmatch(r'u?int(?:8|16|32|64)', match.group()) else match.group()
        ), type_name)

    def beef_type(type_name):
        type_name = plain_type(normalize_type(type_name))
        type_name = re.sub(r'\b(u?int(?:8|16|32|64))_t\b', r'\1', type_name)
        replacements = {'BumpAllocator': 'NoGraphicsAPI.BumpAllocator', 'size_t': 'uint', 'byte': 'uint8', 'char': 'char8'}
        return re.sub(r'\b\w+\b', lambda match: replacements.get(match.group(), match.group()), type_name)

    header = ['#pragma once', '#include <stdint.h>', '#include <stddef.h>', '#include <stdbool.h>',
              'typedef void (*nga_DeleteCallback)(void* context);', '#ifdef __cplusplus', '#include <NoGraphicsAPI/NoGraphicsAPI.hpp>']
    header.extend('#include <NoGraphicsAPIUtility/' + name + '>' for name in utility_configuration['public_api_hashes'])
    for type_name in opaque_types + [name for name, _, _ in enumerations] + list(structures):
        native_type = type_name + '<gpu::byte>' if type_name in ('GpuCpuRange', 'HeapAllocation') else type_name
        header.append('using nga_{} = gpu::{};'.format(type_name, native_type))
    for span_name, element_type in SPAN_ELEMENTS.items():
        native_type = {'ByteSpan': 'ByteSpan', 'CommandBufferSpan': 'Span<gpu::CommandBuffer* const>'}.get(span_name, 'Span<const gpu::{}>'.format(element_type))
        header.append('using nga_{} = gpu::{};'.format(span_name, native_type))
    header.append('#else')
    header.extend('typedef struct nga_{0} nga_{0};'.format(name) for name in opaque_types)
    for enum_name, underlying_type, members in enumerations:
        header.append('typedef {} nga_{};'.format(c_type(underlying_type), enum_name))
        for member_name, expression, _ in members:
            for previous_name, _, _ in members:
                expression = re.sub(r'\b' + previous_name + r'\b', 'NGA_' + enum_name + '_' + previous_name, expression)
            header.append('#define NGA_{0}_{1} ((nga_{0})({2}))'.format(enum_name, member_name, expression))
    header.extend('typedef struct nga_{0} nga_{0};'.format(name) for name in structure_fields)
    for structure_name in list(SPAN_ELEMENTS) + list(structures):
        header.append('struct nga_' + structure_name + ' {')
        for field_type, field_name in structure_fields[structure_name]:
            header.append('    {} {};'.format(c_type(field_type), field_name))
        header.append('};')
    header.extend(['#endif', '#ifdef __cplusplus', 'extern "C" {', '#endif'])
    implementation = ['#include "nographicsapi.h"']
    beef = ['using System;', 'namespace NoGraphicsAPI;', '']
    for type_name in opaque_types:
        beef.extend(['[CRepr]', 'public struct ' + type_name + ' {}'])
    for enum_name, underlying_type, members in enumerations:
        beef.extend(['public enum {} : {}'.format(enum_name, underlying_type), '{'])
        for member_name, _, expression in members:
            for previous_name, _, _ in members:
                expression = re.sub(r'\b' + previous_name + r'\b', beef_identifier(previous_name), expression)
            beef.append('    {} = {},'.format(beef_identifier(member_name), expression))
        beef.append('}')
    for structure_name in list(SPAN_ELEMENTS) + list(structures):
        beef.extend(['[CRepr]', 'public struct ' + structure_name, '{'])
        for field_type, field_name in structure_fields[structure_name]:
            beef.append('    public {} {};'.format(beef_type(field_type), beef_identifier(field_name)))
        if structure_name not in SPAN_ELEMENTS:
            initializer = 'void nga_init_{0}(nga_{0}* value)'.format(structure_name)
            header.append(initializer + ';')
            implementation.append(initializer + ' { *value = {}; }')
            beef.extend(['    public this() { this = default; Initialize(&this); }',
                         '    [CallingConvention(.Cdecl), LinkName("nga_init_' + structure_name + '")]',
                         '    private static extern void Initialize(' + structure_name + '* value);'])
        beef.append('}')
    beef.extend(['public static class GPU', '{', '    [CallingConvention(.Cdecl)]', '    public function void DeleteCallback(void* context);'])
    implementation.append('struct DeferredCallback { nga_DeleteCallback callback; void* context; void operator()() noexcept { callback(context); } };')
    for return_type, function_name, parameters, utility_body in functions:
        return_type = plain_type(normalize_type(return_type))
        validate_type(return_type)
        c_parameters = []
        native_arguments = []
        beef_parameters = []
        beef_native_parameters = []
        beef_arguments = []
        copied_parameters = []
        for parameter in parameters.split(','):
            parameter = parameter.split('=', 1)[0].strip()
            if not parameter:
                continue
            parameter_match = re.fullmatch(r'(.+?)\s+(\w+)', parameter, flags=re.S)
            if not parameter_match:
                raise ValueError(function_name + ': unsupported parameter ' + parameter)
            parameter_type, parameter_name = parameter_match.groups()
            parameter_type = normalize_type(parameter_type)
            value_type = plain_type(parameter_type)
            validate_type(value_type)
            if '&' in parameter_type and ('const' not in parameter_type or value_type not in structure_fields):
                raise ValueError(function_name + ': unsupported reference ' + parameter)
            indirect = value_type in structure_fields
            boundary_type = 'const ' + value_type + '*' if indirect else parameter_type
            c_parameters.append('{} {}'.format(c_type(boundary_type), parameter_name))
            native_arguments.append(('*' if indirect else '') + parameter_name)
            beef_parameter_name = beef_identifier(parameter_name)
            beef_parameters.append('{} {}'.format(beef_type(value_type), beef_parameter_name))
            beef_native_parameters.append('{} {}'.format(beef_type(boundary_type), beef_parameter_name))
            beef_arguments.append(('&' if indirect else '') + beef_parameter_name)
            if indirect:
                copied_parameters.append(beef_parameter_name)
        returns_structure = return_type in structure_fields
        if returns_structure:
            c_parameters.append(c_type(return_type) + '* result')
            beef_native_parameters.append(beef_type(return_type) + '* result')
        signature = '{} nga_{}({})'.format('void' if returns_structure else c_type(return_type), function_name, ', '.join(c_parameters) or 'void')
        header.append(signature + ';')
        result_prefix = '*result = ' if returns_structure else 'return ' if return_type != 'void' else ''
        function_body = utility_body or 'gpu::{}({})'.format(function_name, ', '.join(native_arguments))
        implementation.append(signature + ' { ' + result_prefix + function_body + '; }')
        beef_function_name = pascal_case(function_name)
        beef.extend(['    [CallingConvention(.Cdecl), LinkName("nga_' + function_name + '")]',
                     '    private static extern {} Native{}({});'.format('void' if returns_structure else beef_type(return_type), beef_function_name, ', '.join(beef_native_parameters)),
                     '    public static {} {}({})'.format(beef_type(return_type), beef_function_name, ', '.join(beef_parameters)), '    {'])
        beef.extend('        var ' + parameter_name + ';' for parameter_name in copied_parameters)
        if returns_structure:
            beef.append('        {} result = default;'.format(beef_type(return_type)))
            beef.append('        Native{}({});'.format(beef_function_name, ', '.join(beef_arguments + ['&result'])))
            beef.append('        return result;')
        else:
            beef.append('        {}Native{}({});'.format('return ' if return_type != 'void' else '', beef_function_name, ', '.join(beef_arguments)))
        beef.append('    }')
    beef.extend(['    public static GpuRange GpuRange(GpuHeap heap) { return GpuRange(heap.range); }', '}'])
    header.extend(['#ifdef __cplusplus', '}', '#endif'])
    return {
        'csrc/nographicsapi.h': GENERATED_NOTICE + '\n'.join(header) + '\n',
        'csrc/nographicsapi.cpp': GENERATED_NOTICE + '\n'.join(implementation) + '\n',
        'src/NoGraphicsAPI.bf': GENERATED_NOTICE + '\n'.join(beef) + '\n',
    }


def find_formatter():
    formatter = os.environ.get('CLANG_FORMAT') or shutil.which('clang-format')
    if formatter:
        return formatter
    for edition in ('Professional', 'Community', 'Enterprise', 'BuildTools'):
        candidate = Path('C:/Program Files/Microsoft Visual Studio/2022') / edition / 'VC/Tools/Llvm/x64/bin/clang-format.exe'
        if candidate.is_file():
            return str(candidate)
    raise ValueError('clang-format was not found. Add it to PATH or set CLANG_FORMAT to its executable path.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Report stale generated files without writing them')
    parser.add_argument('--check-tools', action='store_true', help='Check generator prerequisites without generating files')
    arguments = parser.parse_args()
    try:
        formatter = find_formatter()
        subprocess.run([formatter, '--version'], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if arguments.check_tools:
            return 0
        submodule_directory = PROJECT_DIRECTORY / 'submodules/NoGraphicsAPI'
        utility_configuration = json.loads((PROJECT_DIRECTORY / 'tools/utility_bindings.json').read_text(encoding='utf-8'))
        outputs = generate_bindings(submodule_directory, utility_configuration)
        for filename, contents in list(outputs.items()):
            if filename.startswith('csrc/'):
                formatted = subprocess.run([formatter, '--style=file:' + str(submodule_directory / '.clang-format'), '--assume-filename=' + filename],
                                           input=contents.encode('utf-8'), stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
                outputs[filename] = formatted.stdout.decode('utf-8').replace('\r\n', '\n')
        changed_files = []
        for filename, contents in outputs.items():
            destination = PROJECT_DIRECTORY / filename
            if not destination.exists() or destination.read_text(encoding='utf-8') != contents:
                changed_files.append(filename)
        if arguments.check:
            if changed_files:
                print('Bindings need regeneration: ' + ', '.join(changed_files), file=sys.stderr)
                return 1
            print('Generated bindings are up to date.')
            return 0
        # Parse and format every output before replacing any checked-in binding.
        for filename in changed_files:
            destination = PROJECT_DIRECTORY / filename
            destination.parent.mkdir(parents=True, exist_ok=True)
            with destination.open('w', encoding='utf-8', newline='\n') as output_file:
                output_file.write(outputs[filename])
        print('Generated C and Beef bindings ({} changed files).'.format(len(changed_files)))
        return 0
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print('Binding generation failed: ' + str(error), file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.decode('utf-8', errors='replace'), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
